import { test, expect, type Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'

async function fits(page: Page) {
  expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1)
}
async function download(page: Page, label: string) {
  const [file] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: label, exact: true }).click()])
  return readFile((await file.path())!, 'utf8')
}

test('chapter progress, keyboard skip, and desktop/phone layout', async ({ page }, info) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('./')
  await expect(page.getByRole('heading', { level: 1 })).toContainText('From Opportunity')
  await expect(page.locator('.hero-chart svg.recharts-surface').first()).toBeVisible()
  await fits(page)
  await page.screenshot({ path: info.outputPath('home.png'), fullPage: true })
  await page.keyboard.press('Tab')
  await expect(page.getByRole('link', { name: 'Skip to content' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.locator('main')).toBeFocused()
  await page.getByRole('link', { name: 'Start with Maya' }).click()
  await page.getByRole('button', { name: 'Some commuters book a repair at the intended price.' }).click()
  await expect(page.getByText('Correct.')).toBeVisible()
  await page.getByRole('button', { name: 'Mark complete' }).click()
  await page.reload()
  await expect(page.getByText('1 of 9 chapters complete')).toBeVisible()
  await page.getByRole('button', { name: 'Reset progress' }).click()
  await expect(page.getByText('0 of 9 chapters complete')).toBeVisible()
  for (let i = 1; i <= 9; i++) {
    await page.goto(`./#/learn/${i}`)
    await expect(page.getByRole('heading', { name: 'Make a prediction' })).toBeVisible()
    await expect(page.getByRole('heading', { name: 'Try it' })).toBeVisible()
    await expect(page.getByRole('heading', { name: 'Apply it elsewhere' })).toBeVisible()
    await fits(page)
  }
  expect(errors).toEqual([])
})

