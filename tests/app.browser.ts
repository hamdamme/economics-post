test('guided comparisons, deep refresh, replay and versioned import/export', async ({ page }, info) => {
  for (const [route, text] of [['entry', '39 active firms'], ['learning', '44 active firms'], ['capacity', 'First new plant arrives in period 8'], ['reversal', '2 active firms']]) {
    await page.goto(`./#/compare/${route}`)
    await expect(page.getByText(text, { exact: false }).first()).toBeVisible()
    await fits(page)
  }
  await page.reload()
  await expect(page.getByRole('heading', { name: 'What if demand reverses?' })).toBeVisible()
  await page.screenshot({ path: info.outputPath('comparison.png'), fullPage: false })
  await page.getByRole('link', { name: 'Open in market lab' }).last().click()
  await expect(page.getByRole('heading', { name: 'Play the market forward' })).toBeVisible()
  await page.getByRole('button', { name: 'Step', exact: true }).click()
  await expect(page.locator('.range output').first()).toHaveText('2 / 24')
  await page.getByRole('button', { name: 'Reset', exact: true }).click()
  await expect(page.locator('.range output').first()).toHaveText('1 / 24')
  await page.getByRole('button', { name: 'Replay', exact: true }).click()
  await expect.poll(async () => Number((await page.locator('.range output').first().textContent())!.split(' / ')[0])).toBeGreaterThan(1)
  await page.getByRole('button', { name: 'Pause', exact: true }).click()
  const pausedPeriod = await page.locator('.range output').first().textContent()
  await expect(page.getByRole('button', { name: 'Pause', exact: true })).toBeDisabled()
  await expect(page.locator('.range output').first()).toHaveText(pausedPeriod!)
  await page.getByRole('button', { name: 'Show full path' }).click()
  const original = JSON.parse(await download(page, 'Download run JSON'))
  expect(original.config.shockAt).toBe(6)
  expect(original.rows).toHaveLength(24)
  const input = page.getByLabel('Import run JSON')
  await input.setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('{}') })
  await expect(page.getByRole('alert')).toContainText('Unsupported')
  await input.setInputFiles({ name: 'market.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(original)) })
  await expect(page.locator('p[role=status]')).toContainText('Imported settings')
  await page.getByRole('button', { name: 'Show full path' }).click()
  expect(JSON.parse(await download(page, 'Download run JSON'))).toEqual(original)
  expect(await download(page, 'Download timeline CSV')).toContain('discountedNet')
  await page.getByText('Edit simulation settings').click()
  await page.getByLabel('Initial small firms').fill('0')
  await page.getByRole('button', { name: 'Apply settings' }).click()
  await expect(page.locator('p[role=status]')).toContainText('Initial small firms')
  await fits(page)
})

test('warehouse example can be edited, printed, exported and reset', async ({ page }) => {
  await page.goto('./#/worksheet')
  await page.getByRole('button', { name: 'Load warehouse example' }).click()
  const field = page.getByLabel('Business name')
  await expect(field).toHaveValue('Freight-transfer warehouse (fictional)')
  await field.fill('My warehouse')
  await page.getByLabel('Customer and substitutes — Evidence').fill('Confirmed booking')
  await page.reload()
  await expect(field).toHaveValue('My warehouse')
  expect(JSON.parse(await download(page, 'Download JSON')).sections[0].evidence).toBe('Confirmed booking')
  expect(await download(page, 'Download Markdown')).toContain('## Adverse case')
  await page.evaluate(() => { window.print = () => { document.body.dataset.printCalled = 'true' } })
  await page.getByRole('button', { name: 'Print / save PDF' }).click()
  await expect(page.locator('body')).toHaveAttribute('data-print-called', 'true')
  await page.emulateMedia({ media: 'print' })
  await expect(page.locator('.saved-text').filter({ hasText: 'Confirmed booking' })).toBeVisible()
  await page.emulateMedia({ media: 'screen' })
  await page.getByRole('button', { name: 'Reset worksheet' }).click()
  await expect(field).toHaveValue('')
  await fits(page)
})
